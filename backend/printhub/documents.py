"""Upload storage, validation and retention.

Uploaded bytes are written under a random internal name; the original
filename is kept only as display metadata and is never used as a path.
"""
from __future__ import annotations

import hashlib
import json
import os
import secrets
import subprocess
import sys
import unicodedata
from pathlib import Path
from typing import AsyncIterator

from .config import Config
from .db import Database, dumps, loads, now
from .events import EventLog

ALLOWED_EXTENSIONS = {".pdf", ".jpg", ".jpeg", ".png", ".webp"}
WORKER = Path(__file__).with_name("inspect_worker.py")

# Statuses of items that still need their file on disk.
ACTIVE_ITEM_STATUSES = ("preparing", "ready", "submitting", "queued", "held", "processing")


class UploadError(Exception):
    def __init__(self, code: str, message: str, status: int = 400):
        super().__init__(message)
        self.code = code
        self.message = message
        self.status = status


def clean_display_name(name: str) -> str:
    """Make a filename safe to *display*. It is never used as a filesystem path."""
    name = unicodedata.normalize("NFC", name or "")
    name = name.replace("\\", "/").split("/")[-1]
    name = "".join(ch for ch in name if unicodedata.category(ch)[0] != "C").strip().strip(".")
    if not name:
        name = "Untitled"
    if len(name) > 160:
        stem, ext = os.path.splitext(name)
        name = stem[: 160 - len(ext)] + ext
    return name


def _limit_resources(memory_mb: int, cpu_s: int):  # pragma: no cover - runs in child
    def apply():
        try:
            import resource

            resource.setrlimit(resource.RLIMIT_CPU, (cpu_s, cpu_s))
            if sys.platform.startswith("linux"):
                limit = memory_mb * 1024 * 1024
                resource.setrlimit(resource.RLIMIT_AS, (limit, limit))
        except (ImportError, ValueError, OSError):
            pass

    return apply


class FileStore:
    def __init__(self, config: Config, db: Database, events: EventLog):
        self.config = config
        self.db = db
        self.events = events
        self.dir = config.upload_dir
        self.dir.mkdir(parents=True, exist_ok=True)
        os.chmod(self.dir, 0o700)

    def path_for(self, storage_name: str) -> Path:
        # storage names are generated by us; reject anything else defensively
        if not storage_name or "/" in storage_name or storage_name.startswith("."):
            raise ValueError("invalid storage name")
        return self.dir / storage_name

    async def receive(
        self,
        owner_id: int,
        original_name: str,
        declared_length: int | None,
        chunks: AsyncIterator[bytes],
        retention_hours: int,
        correlation_id: str,
    ) -> dict:
        display = clean_display_name(original_name)
        ext = os.path.splitext(display)[1].lower()
        file_id = secrets.token_hex(12)
        log = dict(correlation_id=correlation_id, user_id=owner_id)
        details = {"file_id": file_id, "extension": ext or "(none)", "declared_bytes": declared_length}
        self.events.record("upload", "upload.received", "Upload started", details=details, **log)

        if ext not in ALLOWED_EXTENSIONS:
            self.events.record("validation", "upload.rejected", "Unsupported file extension", level="warning", details=details, **log)
            raise UploadError(
                "unsupported_type",
                f"“{display}” isn't a supported type. Upload PDF, JPEG, PNG or WebP files. "
                "Word, Excel and other Office files need to be saved as PDF first.",
                415,
            )
        if declared_length is not None and declared_length > self.config.max_file_bytes:
            self.events.record("validation", "upload.rejected", "File exceeds size limit", level="warning", details=details, **log)
            raise UploadError("too_large", f"“{display}” is larger than the {self.config.max_file_mb} MB limit.", 413)

        storage_name = f"{file_id}.bin"
        path = self.path_for(storage_name)
        digest = hashlib.sha256()
        size = 0
        try:
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as fh:
                async for chunk in chunks:
                    size += len(chunk)
                    if size > self.config.max_file_bytes:
                        raise UploadError("too_large", f"“{display}” is larger than the {self.config.max_file_mb} MB limit.", 413)
                    digest.update(chunk)
                    fh.write(chunk)
            if size == 0:
                raise UploadError("empty", f"“{display}” is empty.")
        except BaseException as exc:
            path.unlink(missing_ok=True)
            reason = exc.code if isinstance(exc, UploadError) else "interrupted"
            self.events.record(
                "validation", "upload.rejected", "Upload did not complete", level="warning",
                details={**details, "reason": reason, "received_bytes": size}, **log,
            )
            raise

        result = self._inspect(path, file_id)
        if not result.get("ok"):
            path.unlink(missing_ok=True)
            for extra in (self.dir / f"{file_id}.print.png",):
                extra.unlink(missing_ok=True)
            self.events.record(
                "validation", "upload.rejected", "File failed content validation", level="warning",
                details={**details, "bytes": size, "code": result.get("code")}, **log,
            )
            raise UploadError(result.get("code", "invalid"), f"“{display}”: {result.get('message')}", 422)

        t = now()
        notes = result.get("notes", [])
        if result["mime"] != {".pdf": "application/pdf", ".png": "image/png", ".webp": "image/webp"}.get(ext, "image/jpeg"):
            notes.insert(0, f"The file name ends in {ext} but the content is {result['mime'].split('/')[1].upper()}; it is handled by its content.")
        record = {
            "id": file_id,
            "owner_id": owner_id,
            "original_name": display,
            "kind": result["kind"],
            "mime": result["mime"],
            "size_bytes": size,
            "sha256": digest.hexdigest(),
            "pages": result.get("pages"),
            "width_pt": result.get("width_pt"),
            "height_pt": result.get("height_pt"),
            "storage_name": storage_name,
            "print_name": result.get("print_name"),
            "print_mime": result.get("print_mime"),
            "notes": dumps(notes),
            "status": "ready",
            "created_at": t,
            "expires_at": t + retention_hours * 3600,
        }
        cols = ", ".join(record)
        self.db.execute(f"INSERT INTO files ({cols}) VALUES ({', '.join('?' * len(record))})", tuple(record.values()))
        self.events.record(
            "validation", "upload.accepted", "File validated and stored",
            details={**details, "bytes": size, "mime": result["mime"], "pages": result.get("pages"),
                     "converted_copy": bool(result.get("print_name")), "notes": len(notes)},
            **log,
        )
        return self.public(self.get(file_id))

    def add_generated_pdf(self, owner_id: int, display_name: str, render, retention_hours: int) -> dict:
        """Store a PDF produced by the hub itself (e.g. a test page)."""
        file_id = secrets.token_hex(12)
        storage_name = f"{file_id}.bin"
        path = self.path_for(storage_name)
        render(path)
        os.chmod(path, 0o600)
        data = path.read_bytes()
        t = now()
        self.db.execute(
            "INSERT INTO files (id, owner_id, original_name, kind, mime, size_bytes, sha256, pages, width_pt, height_pt,"
            " storage_name, notes, status, created_at, expires_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (file_id, owner_id, display_name, "pdf", "application/pdf", len(data), hashlib.sha256(data).hexdigest(),
             1, 612.0, 792.0, storage_name, "[]", "ready", t, t + retention_hours * 3600),
        )
        return self.get(file_id)

    def _inspect(self, path: Path, file_id: str) -> dict:
        cmd = [
            sys.executable, "-I", str(WORKER), str(path),
            str(self.config.max_pdf_pages), str(self.config.max_image_megapixels * 1_000_000), str(self.dir), file_id,
        ]
        try:
            proc = subprocess.run(
                cmd,
                capture_output=True,
                timeout=self.config.inspect_timeout_s,
                preexec_fn=_limit_resources(self.config.inspect_memory_mb, self.config.inspect_timeout_s),
                # -I ignores PYTHON* variables; the venv's site-packages still load.
                env={"PATH": os.environ.get("PATH", ""), "LANG": "C.UTF-8"},
            )
        except subprocess.TimeoutExpired:
            return {"ok": False, "code": "too_slow", "message": "This file took too long to process. It may be damaged or very complex."}
        try:
            return json.loads(proc.stdout.decode() or "{}") or {
                "ok": False, "code": "inspect_failed", "message": "This file could not be processed."
            }
        except json.JSONDecodeError:
            return {"ok": False, "code": "inspect_failed", "message": "This file could not be processed."}

    # --- queries -----------------------------------------------------------
    def get(self, file_id: str) -> dict | None:
        return self.db.one("SELECT * FROM files WHERE id = ?", (file_id,))

    def list_for(self, owner_id: int) -> list[dict]:
        rows = self.db.all(
            "SELECT f.*, (SELECT COUNT(*) FROM job_items i WHERE i.file_id = f.id) AS used_in_jobs"
            " FROM files f WHERE f.owner_id = ? AND f.status = 'ready' ORDER BY f.created_at",
            (owner_id,),
        )
        return [{**self.public(r), "used_in_jobs": r["used_in_jobs"]} for r in rows]

    @staticmethod
    def public(row: dict) -> dict:
        return {
            "id": row["id"],
            "name": row["original_name"],
            "kind": row["kind"],
            "mime": row["mime"],
            "size_bytes": row["size_bytes"],
            "pages": row["pages"],
            "width_pt": row["width_pt"],
            "height_pt": row["height_pt"],
            "notes": loads(row["notes"], []),
            "status": row["status"],
            "created_at": row["created_at"],
            "expires_at": row["expires_at"],
            "available": row["status"] == "ready",
        }

    def print_path(self, row: dict) -> tuple[Path, str]:
        if row.get("print_name"):
            return self.path_for(row["print_name"]), row["print_mime"]
        return self.path_for(row["storage_name"]), row["mime"]

    def in_active_job(self, file_id: str) -> bool:
        marks = ",".join("?" * len(ACTIVE_ITEM_STATUSES))
        return bool(
            self.db.one(f"SELECT 1 FROM job_items WHERE file_id = ? AND status IN ({marks}) LIMIT 1", (file_id, *ACTIVE_ITEM_STATUSES))
        )

    def delete(self, row: dict, reason: str, correlation_id: str | None = None) -> None:
        for name in (row["storage_name"], row.get("print_name")):
            if name:
                self.path_for(name).unlink(missing_ok=True)
        self.db.execute("UPDATE files SET status = 'deleted', deleted_at = ? WHERE id = ?", (now(), row["id"]))
        self.events.record(
            "cleanup", "file.deleted", f"Stored file removed ({reason})",
            user_id=row["owner_id"], correlation_id=correlation_id, details={"file_id": row["id"], "reason": reason},
        )

    def cleanup_expired(self) -> dict:
        """Delete expired files that are not needed by an active job."""
        removed = kept = 0
        for row in self.db.all("SELECT * FROM files WHERE status = 'ready' AND expires_at < ?", (now(),)):
            if self.in_active_job(row["id"]):
                kept += 1
                continue
            self.delete(row, "retention period ended")
            removed += 1
        # Orphans: files on disk with no database row (e.g. crash mid-upload)
        known = {r["storage_name"] for r in self.db.all("SELECT storage_name FROM files WHERE status = 'ready'")}
        known |= {r["print_name"] for r in self.db.all("SELECT print_name FROM files WHERE status = 'ready' AND print_name IS NOT NULL")}
        orphans = 0
        for entry in self.dir.iterdir():
            if entry.is_file() and entry.name not in known and now() - entry.stat().st_mtime > 3600:
                entry.unlink(missing_ok=True)
                orphans += 1
        return {"removed": removed, "kept_for_active_jobs": kept, "orphans_removed": orphans}
